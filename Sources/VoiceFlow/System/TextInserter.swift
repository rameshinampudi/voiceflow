import AppKit
import CoreGraphics

/// Puts text into whatever app has focus: clipboard + ⌘V, then the user's clipboard comes back.
@MainActor
enum TextInserter {
    /// Tags our synthetic key events so the hotkey tap ignores them.
    static let syntheticEventMarker: Int64 = 0x56_46_4C  // "VFL"

    enum Outcome { case pasted, pastedAndKeptOnClipboard }

    static func insert(_ text: String, restoreClipboard: Bool) async -> Outcome {
        let pasteboard = NSPasteboard.general
        // When no focused element is visible to Accessibility we can't be sure the paste landed,
        // so leave the text on the clipboard for a manual ⌘V.
        let focusKnown = AXContext.focusedElement() != nil
        let snapshot = (restoreClipboard && focusKnown) ? PasteboardSnapshot(pasteboard) : nil

        write(text, to: pasteboard, transient: snapshot != nil)
        let ourChange = pasteboard.changeCount
        try? await Task.sleep(for: .milliseconds(20))
        postKeystroke(keyCode: 9, flags: .maskCommand)  // ⌘V

        guard let snapshot else { return .pastedAndKeptOnClipboard }
        try? await Task.sleep(for: .milliseconds(450))
        if pasteboard.changeCount == ourChange {
            snapshot.restore(to: pasteboard)
        }
        return .pasted
    }

    /// Command Mode fallback when Accessibility can't read the selection: ⌘C and read it back.
    static func copySelectionViaClipboard() async -> String? {
        let pasteboard = NSPasteboard.general
        let snapshot = PasteboardSnapshot(pasteboard)
        let before = pasteboard.changeCount
        postKeystroke(keyCode: 8, flags: .maskCommand)  // ⌘C
        for _ in 0..<12 where pasteboard.changeCount == before {
            try? await Task.sleep(for: .milliseconds(25))
        }
        guard pasteboard.changeCount != before else { return nil }
        let copied = pasteboard.string(forType: .string)
        snapshot.restore(to: pasteboard)
        guard let copied, !copied.isEmpty else { return nil }
        return copied
    }

    static func postKeystroke(keyCode: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: isDown) else { continue }
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: syntheticEventMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    private static func write(_ text: String, to pasteboard: NSPasteboard, transient: Bool) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            // Convention honored by clipboard managers: don't record this entry.
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        pasteboard.writeObjects([item])
    }
}

/// A full copy of the clipboard (every item, every type) so it can be put back.
struct PasteboardSnapshot {
    private let items: [[NSPasteboard.PasteboardType: Data]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}
